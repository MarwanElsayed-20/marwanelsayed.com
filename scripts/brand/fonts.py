# Font files the brand needs, derived from the site's own variable font. Run only when the font
# changes; the outputs are committed. Needs Python 3 with fontTools and brotli (a local tool,
# not a project dependency):
#
#   python scripts/brand/fonts.py
#
# 1. src/fonts/inter-tight-share-{400,700}.ttf: static instances for the share images
#    (next/og cannot read WOFF2 or variable fonts).
# 2. src/lib/brand/wordmark.ts: the header wordmark (bold, uppercase, tracked -0.025em) as
#    outlines with the font's own kerning, for the lockup files.
import json
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/fonts/inter-tight-roman.woff2"
WORDMARK = "MARWAN ELSAYED"
TRACKING_EM = -0.025


def instance(weight):
    # Keep the source's timestamp so a re-run writes identical files.
    source = TTFont(SOURCE, recalcTimestamp=False)
    font = instantiateVariableFont(source, {"wght": weight}, updateFontNames=False)
    font.flavor = None
    out = ROOT / f"src/fonts/inter-tight-share-{weight}.ttf"
    font.save(out)
    return out


def kerning(font):
    """Pair adjustments from the GPOS kern feature (formats 1 and 2, inside extensions too)."""
    gpos = font["GPOS"].table
    indices = set()
    for record in gpos.FeatureList.FeatureRecord:
        if record.FeatureTag == "kern":
            indices.update(record.Feature.LookupListIndex)
    tables = []
    for index in sorted(indices):
        lookup = gpos.LookupList.Lookup[index]
        for sub in lookup.SubTable:
            sub = sub.ExtSubTable if lookup.LookupType == 9 else sub
            if hasattr(sub, "PairSet") or hasattr(sub, "Class1Record"):
                tables.append(sub)

    def pair(first, second):
        for sub in tables:
            glyphs = sub.Coverage.glyphs
            if first not in glyphs:
                continue
            if sub.Format == 1:
                for record in sub.PairSet[glyphs.index(first)].PairValueRecord:
                    if record.SecondGlyph == second:
                        return getattr(record.Value1, "XAdvance", 0) or 0
            else:
                c1 = sub.ClassDef1.classDefs.get(first, 0)
                c2 = sub.ClassDef2.classDefs.get(second, 0)
                value = getattr(sub.Class1Record[c1].Class2Record[c2].Value1, "XAdvance", 0) or 0
                if value:
                    return value
        return 0

    return pair


def wordmark(path):
    font = TTFont(path)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    cap = font["OS/2"].sCapHeight
    names = [cmap[ord(char)] for char in WORDMARK]
    pair = kerning(font)
    pen, bounds = SVGPathPen(glyphs), BoundsPen(glyphs)
    x = 0.0
    for i, name in enumerate(names):
        for target in (pen, bounds):
            glyphs[name].draw(TransformPen(target, (1, 0, 0, -1, x, cap)))
        if i + 1 < len(names):
            x += font["hmtx"][name][0] + pair(name, names[i + 1]) + TRACKING_EM * font["head"].unitsPerEm
    x_min, _, x_max, _ = bounds.bounds
    data = {"capHeight": cap, "xMin": round(x_min, 1), "xMax": round(x_max, 1), "d": pen.getCommands()}
    body = ",\n".join(f"  {key}: {json.dumps(value)}" for key, value in data.items())
    (ROOT / "src/lib/brand/wordmark.ts").write_text(
        "/**\n"
        f' * "{WORDMARK}" in Inter Tight 700, tracked {TRACKING_EM}em with the font\'s kerning, as outlines in\n'
        " * font units (y down, baseline at the cap height). Generated by scripts/brand/fonts.py; do not edit.\n"
        " */\n"
        f"export const wordmark = {{\n{body},\n}} as const;\n",
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    instance(400)
    wordmark(instance(700))
    print("Wrote the share fonts and src/lib/brand/wordmark.ts")
