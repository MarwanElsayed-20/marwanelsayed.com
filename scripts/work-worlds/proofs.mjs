// Writes the small, ready-made captures the Work index lays on a project's colour world:
// public/work-proofs/<slug>.webp (the card) and <slug>-screen.webp (a second screen), plus their
// sizes in src/content/site/work-proofs.ts. They are static files, so a first hover never waits
// for the image optimiser. Run: pnpm worlds:build
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const nextRequire = createRequire(realpathSync(join(root, "node_modules", "next", "package.json")));
const sharp = nextRequire("sharp");

const slugs = [
  ...readFileSync(join(root, "src/content/projects/work-order.ts"), "utf8").matchAll(
    /^\s+"([a-z0-9-]+)",$/gm,
  ),
].map((match) => match[1]);

const out = join(root, "public", "work-proofs");
mkdirSync(out, { recursive: true });

async function write(source, target, width) {
  const { info } = await sharp(source)
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 78 })
    .toFile(join(out, target))
    .then((info) => ({ info }));
  return { width: info.width, height: info.height };
}

const sizes = {};
for (const slug of slugs) {
  const base = join(root, "public", "projects", slug);
  const screens = readdirSync(join(base, "screens"))
    .filter((name) => /\.(png|jpe?g|webp)$/i.test(name))
    .sort();
  const second = screens[1] ?? screens[0];
  sizes[slug] = {
    card: await write(join(base, "card.png"), `${slug}.webp`, 1280),
    screen: await write(join(base, "screens", second), `${slug}-screen.webp`, 960),
  };
}
const size = "{ width: number; height: number }";
writeFileSync(
  join(root, "src/content/site/work-proofs.ts"),
  `// Generated by scripts/work-worlds/proofs.mjs (pnpm worlds:build). Do not edit.\nexport const workProofSizes: Readonly<Record<string, { card: ${size}; screen: ${size} }>> = ${JSON.stringify(sizes, null, 2)};\n`,
);
console.log(`${slugs.length} projects`);
